def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(prog="nc", add_help=True)
    p.add_argument("--version", action="version", version=f"NC {nc.__version__}")
    p.add_argument("target", nargs="?", help="Path to .nc file or URL to .nc")
    p.add_argument("--learn", nargs="?", const="", help="Start learn mode (optional topic)")
    p.add_argument("--base", default=None, help="Base folder/URL for resolving relative imports")
    p.add_argument("--libs", action="append", default=[], help="Extra library search path (repeatable)")
    p.add_argument("--allow-http", action="store_true", help="Allow http:// imports (default: https only)")
    p.add_argument("--allow-private", action="store_true", help="Allow private/localhost URL imports (default blocked)")
    p.add_argument("--no-ui", action="store_true", help="Disable __TWIN__ UI output")
    p.add_argument("--no-log", action="store_true", help="Disable step logs")
    p.add_argument("--exe", action="store_true", help="Build the local .nc file into a standalone executable via PyInstaller")
    p.add_argument("--pack-nce", nargs=2, metavar=("SOURCE", "OUTPUT"), help="Create an encrypted .nce package from a .nc file or folder")
    p.add_argument("--nce-entry", default=None, help="Entrypoint inside the .nce package, for example main.nc")
    p.add_argument("--nce-password", default=None, help="Password for reading or creating .nce packages")

    args = p.parse_args(argv)

    # Learn mode
    if args.learn is not None:
        topic = args.learn.strip() or None
        nc.run_learn(topic)
        return 0

    if not args.target:
        if not args.pack_nce:
            p.print_help()
            return 2

    policy = nc.NCPolicy(
        allow_http=bool(args.allow_http),
        allow_private_hosts=bool(args.allow_private),
    )

    if args.nce_password:
        os.environ["NC_NCE_PASSWORD"] = str(args.nce_password)

    if args.pack_nce:
        src, out = args.pack_nce
        try:
            out_path = nc.create_nce(src, out, password=args.nce_password, entrypoint=args.nce_entry)
            print("NC NCE:", out_path)
            return 0
        except Exception as e:
            print(nc.format_exception(e), file=sys.stderr)
            return 1

    target = args.target

    # Allow accidental URL/file fragments like "wormpad.nc#"
    target = target.split("#", 1)[0]

    # For local files: allow calling without .nc/.nce extension
    if (not is_url(target)) and (not target.lower().endswith((".nc", ".nce"))):
        if os.path.isfile(target + ".nc"):
            target = target + ".nc"
        elif os.path.isfile(target + ".nce"):
            target = target + ".nce"

    base = args.base or compute_base(target)

    search_paths = []
    # default search paths for local usage
    if not is_url(base):
        search_paths.extend([base, os.path.join(base, "libs")])
    # additional libs from args
    for lp in args.libs:
        search_paths.append(lp)

    try:
        if args.exe:
            exe_path = build_exe_from_nc(
                target=target,
                policy=policy,
                base=base,
                search_paths=search_paths,
                enable_ui=(not args.no_ui),
            )
            print("NC EXE:", exe_path)
            return 0

        if is_url(target):
            text = read_text_from_target(target, policy)
            if args.no_log:
                text = text + "\n\n# __NC_CONSOLE_NO_LOG__\n"
            nc.run_text(
                text,
                base=base,
                extra_paths=search_paths,
                policy=policy,
                enable_ui=(not args.no_ui),
                source_name=target,
            )
        elif target.lower().endswith(".nce"):
            nc.run_file(target, policy=policy, enable_ui=(not args.no_ui), extra_paths=search_paths)
        else:
            text = read_text_from_target(target, policy)
            if args.no_log:
                text = text + "\n\n# __NC_CONSOLE_NO_LOG__\n"
            nc.run_text(
                text,
                base=base,
                extra_paths=search_paths,
                policy=policy,
                enable_ui=(not args.no_ui),
                source_name=os.path.abspath(target),
            )
        return 0
    except Exception as e:
        print(nc.format_exception(e), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
