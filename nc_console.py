def is_url(s: str) -> bool:
    return s.startswith("https://") or s.startswith("http://")


def read_text_from_target(target: str, policy: nc.NCPolicy) -> str:
    if is_url(target):
        return nc._fetch_url_text(target, policy)
    if target.lower().endswith(".nce"):
        text, _base, _source = nc.nce_read_entry_text(target, policy=policy)
        return text
    # local file
    with open(target, "r", encoding="utf-8", errors="replace") as f:
        return f.read()


def compute_base(target: str) -> str:
    if is_url(target):
        # base = url directory
        return target.rsplit("/", 1)[0] + "/"
    # local file directory
    return os.path.dirname(os.path.abspath(target)) or os.getcwd()


def _safe_exe_name_from_target(target: str) -> str:
    base = os.path.basename(target)
    if base.lower().endswith(".nc"):
        base = base[:-3]
    if base.lower().endswith(".nce"):
        base = base[:-4]
    base = base.strip() or "nc_app"
    cleaned = []
    for ch in base:
        cleaned.append(ch if (ch.isalnum() or ch in ("_", "-", ".")) else "_")
    return "".join(cleaned).strip("._") or "nc_app"


def _existing_search_paths(paths: list[str]) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    for raw in paths or []:
        try:
            p = os.path.abspath(str(raw))
        except Exception:
            continue
        if not os.path.isdir(p):
            continue
        key = os.path.normcase(p)
        if key in seen:
            continue
        seen.add(key)
        out.append(p)
    return out


